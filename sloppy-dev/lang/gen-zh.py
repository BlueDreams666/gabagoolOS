#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""zh.py -> apps/sloppy/sloppy_lang_zh.h

Chinese is the seventh language (sloppy_language 6). The five-column table
(sloppy_lang_table.h) is append-only and stays as it is: Chinese has a
table of its own, one row a phrase, { English, Chinese }, keyed by the same
English, read by sl_tr() for language 6. To add a phrase: append its row to
sloppy_lang_table.h (and translations.py / arabic.py) as before, add its
Chinese to zh.py, then run this. Every row of the main table must have its
Chinese, or this stops and names the missing ones."""
import ast
import re
from pathlib import Path

from zh import ZH

ROOT = Path(__file__).resolve().parents[2]


def c_str(s):
    return '"' + s.replace('\\', '\\\\').replace('"', '\\"').replace('\n', '\\n') + '"'


def main():
    keys = []
    for line in (ROOT / "apps/sloppy/sloppy_lang_table.h").read_text(encoding="utf-8").splitlines():
        m = re.match(r'\{ ("(?:[^"\\]|\\.)*")', line)
        if m:
            keys.append(ast.literal_eval(m.group(1)))
    keys = list(dict.fromkeys(keys))
    missing = [k for k in keys if k not in ZH]
    if missing:
        raise SystemExit(f"zh.py: no Chinese for {missing}")
    unknown = [k for k in ZH if k not in keys]
    if unknown:   # a phrase gone from the main table: take it out of zh.py too
        raise SystemExit(f"zh.py: no row in sloppy_lang_table.h for {unknown}")
    for k in keys:
        if re.findall(r'%l?[sdu]', k) != re.findall(r'%l?[sdu]', ZH[k]):
            raise SystemExit(f"zh.py: {k!r} and its Chinese take different printf arguments")
    lines = ["/* Generated by sloppy-dev/lang/gen-zh.py from zh.py. Do not edit. */"]
    lines += ["{ %s, %s }," % (c_str(k), c_str(ZH[k])) for k in keys]
    (ROOT / "apps/sloppy/sloppy_lang_zh.h").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"{len(keys)} phrases -> apps/sloppy/sloppy_lang_zh.h")


if __name__ == "__main__":
    main()
