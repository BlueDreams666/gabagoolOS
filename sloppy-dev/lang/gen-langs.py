#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""it.py, nl.py, pt.py, pl.py, cs.py, ru.py, ja.py -> apps/sloppy/sloppy_lang_<code>.h

Languages 7 to 13 (Italiano, Nederlands, Português (Brasil), Polski,
Čeština, Русский, 日本語) have a table each, as Chinese does (gen-zh.py):
one row a phrase, { English, translation }, keyed by the same English as
sloppy_lang_table.h, read by sl_tr(). To add a phrase, append it with
append.py (all fourteen languages), which runs this. Every row of the main
table must have its translation in every language, or this stops and
names the missing ones. Run with nothing changed, it leaves the headers
byte for byte as they are.
    python3 sloppy-dev/lang/gen-langs.py"""
import ast
import re
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
# sloppy_language order; the dict in <code>.py is named <CODE>
LANGS = ("it", "nl", "pt", "pl", "cs", "ru", "ja")
FMT = re.compile(r'%[-+0#]*[0-9]*(?:\.[0-9]+)?(?:l|ll|z|h)?[sducxXf%]')


def c_str(s):
    return '"' + s.replace('\\', '\\\\').replace('"', '\\"').replace('\n', '\\n') + '"'


def load(code):
    """the dict, read from bytes: Python 3.9's tokenizer trips on long UTF-8 lines in a file it reads itself"""
    p = HERE / f"{code}.py"
    g = {}
    exec(compile(p.read_bytes(), str(p), "exec"), g)
    return g[code.upper()]


def keys():
    out = []
    for line in (ROOT / "apps/sloppy/sloppy_lang_table.h").read_text(encoding="utf-8").splitlines():
        m = re.match(r'\{ ("(?:[^"\\]|\\.)*")', line)
        if m:
            out.append(ast.literal_eval(m.group(1)))
    return list(dict.fromkeys(out))


def main():
    ks = keys()
    bad = []
    for code in LANGS:
        d = load(code)
        missing = [k for k in ks if k not in d]
        unknown = [k for k in d if k not in ks]
        if missing: bad.append(f"{code}.py: no translation for {missing}")
        if unknown: bad.append(f"{code}.py: no row in sloppy_lang_table.h for {unknown}")
        for k in ks:
            if k in d and FMT.findall(k) != FMT.findall(d[k]):
                bad.append(f"{code}.py: {k!r} and its translation take different printf arguments")
            if k in d and re.search(r'zune|woof', d[k], re.I):
                bad.append(f"{code}.py: {d[k]!r}: the theme is Zule, the mode is USB mode")
    if bad:
        raise SystemExit("\n".join(bad))
    for code in LANGS:
        d = load(code)
        lines = [f"/* Generated by sloppy-dev/lang/gen-langs.py from {code}.py. Do not edit. */"]
        lines += ["{ %s, %s }," % (c_str(k), c_str(d[k])) for k in ks]
        (ROOT / f"apps/sloppy/sloppy_lang_{code}.h").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"{len(ks)} phrases x {len(LANGS)} languages -> apps/sloppy/sloppy_lang_{{{','.join(LANGS)}}}.h")


if __name__ == "__main__":
    main()
