#!/usr/bin/env python3
"""Regenerate SloppyOS UI fonts with matching static Hebrew weights.

Requires fontTools and lv_font_conv. Run from anywhere; the source tree is
resolved relative to this script. Set LV_FONT_CONV to the converter path.
"""

import os
import subprocess
import tempfile
from pathlib import Path

from fontTools.ttLib import TTFont
from fontTools.varLib.instancer import instantiateVariableFont


ROOT = Path(__file__).resolve().parents[1]
SOURCES = ROOT / "sloppy-dev" / "fonts-src"
OUTPUT = ROOT / "apps" / "sloppy" / "fonts"
LATIN_RANGE = "0x20-0x7E,0xA0-0x17F,0x2013-0x2014,0x2018-0x201E,0x2022,0x2026,0x20AC"
HEBREW_RANGE = "0x590-0x5FF"
FONTS = (
    ("regular", 16, 16),
    ("regular", 18, 18),
    ("semibold", 18, 18),
    ("semibold", 21, 20),
    ("semibold", 23, 22),
    ("semibold", 26, 24),
    ("semibold", 30, 28),
    ("bold", 28, 28),
)
WEIGHTS = {"regular": 400, "semibold": 600, "bold": 700}


def main():
    converter = os.environ.get("LV_FONT_CONV", "lv_font_conv")
    with tempfile.TemporaryDirectory(prefix="sloppy-hebrew-") as temp:
        hebrew = {}
        for style, weight in WEIGHTS.items():
            font = TTFont(SOURCES / "NotoSansHebrew.ttf")
            font = instantiateVariableFont(font, {"wght": weight, "wdth": 100})
            path = Path(temp) / f"NotoSansHebrew-{style}.ttf"
            font.save(path)
            hebrew[style] = path

        for style, size, fallback in FONTS:
            name = f"ss_{style}_{size}"
            latin = SOURCES / f"SourceSans3-{style.title()}.ttf"
            args = [
                converter, "--font", str(latin), "-r", LATIN_RANGE,
                "--font", str(hebrew[style]), "-r", HEBREW_RANGE,
                "--size", str(size), "--bpp", "4", "--format", "lvgl",
                "--no-compress", "--lv-include", "lvgl.h",
                "--lv-font-name", name,
                # Arabic, then Montserrat's symbols (generate-arabic-fonts.py)
                "--lv-fallback", f"ss_arabic_{size}",
                "-o", str(OUTPUT / f"{name}.c"),
            ]
            subprocess.run(args, check=True)
            output = OUTPUT / f"{name}.c"
            generated = output.read_text()
            lines = generated.splitlines(keepends=True)
            lines[3] = (
                f" * Opts: generated by sloppy-dev/generate-ui-fonts.py "
                f"(Hebrew wght={WEIGHTS[style]})\n"
            )
            output.write_text("".join(lines))
            print(f"Generated {name} with Hebrew weight {WEIGHTS[style]}")


if __name__ == "__main__":
    main()
