#!/usr/bin/env python3
"""words-<id>.txt -> apps/sloppy/sloppy_kb_dict.h: one string a language,
its words lower case, the commonest first, each once."""
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
IDS = ["en", "es", "fr", "de", "it", "pt", "nl", "pl", "cs", "ru", "he", "ar"]


def c_str(s):
    return '"' + s.replace('\\', '\\\\').replace('"', '\\"') + '"'


def main():
    out = ["/* Generated by sloppy-dev/kb/gen-kb-dict.py from sloppy-dev/kb/words-*.txt. Do not edit.",
           " * The words a glide or a suggestion can become, the commonest first. */"]
    total = 0
    for i in IDS:
        seen, words = set(), []
        for w in (Path(__file__).parent / f"words-{i}.txt").read_text(encoding="utf-8").split():
            w = w.lower()
            if len(w) < 2 or w in seen:
                continue
            seen.add(w)
            words.append(w)
        text = " ".join(words)
        total += len(text.encode()) + 1
        out.append(f"static const char kb_dict_{i}[] =")
        line = ""
        for w in words:
            if len(line) + len(w) > 90:
                out.append("    " + c_str(line))
                line = ""
            line += w + " "
        out.append("    " + c_str(line.rstrip()) + ";")
        print(f"{i}: {len(words)} words")
    (ROOT / "apps/sloppy/sloppy_kb_dict.h").write_text("\n".join(out) + "\n", encoding="utf-8")
    print(f"{total} bytes")


if __name__ == "__main__":
    main()
