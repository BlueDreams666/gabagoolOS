#!/usr/bin/env python3
"""The pinyin keyboard's data -> apps/sloppy/sloppy_pinyin.h, and the
Chinese letter packs' code points -> cjk-codepoints.txt.

Needs Unihan (https://www.unicode.org/Public/UCD/latest/ucd/Unihan.zip,
Unicode licence): python3 gen-pinyin.py <Unihan folder>

The characters: the 3,500 of the 2013 Table of General Standard Chinese
Characters' first level (kTGH) and GB 2312's 3,755 of level one (kGB0),
together 3,874. Each under every reading Unihan gives it, ordered by how
often that reading is heard (kHanyuPinlu, from the Xiandai Hanyu Pinlu
Cidian); characters it does not count follow, in GB 2312 order.

The letter packs also hold the traditional forms of the first 3,500
(kTraditionalVariant), so Taiwanese and Hong Kong titles show, and the
Japanese common-use kanji (kJoyoKanji) the rest lack, plus kana,
CJK punctuation and full-width forms, and every character of the Chinese
translation and of pinyin-phrases.txt."""
import collections
import sys
import unicodedata as ud
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]


def plain(s):
    s = ud.normalize('NFD', s).replace('u\u0308', 'v')          # ü is typed v
    return ''.join(c for c in s if not ud.combining(c)).lower()


def main():
    U = Path(sys.argv[1])
    f = collections.defaultdict(dict)
    for fn in ('Unihan_OtherMappings.txt', 'Unihan_Readings.txt', 'Unihan_Variants.txt'):
        for line in (U / fn).read_text(encoding='utf-8').splitlines():
            if line.startswith('U+'):
                cp, k, v = line.split('\t', 2)
                f[int(cp[2:], 16)][k] = v
    tgh1 = {c for c, d in f.items() if 'kTGH' in d and int(d['kTGH'].split(':')[1]) <= 3500}
    gb1 = {c for c, d in f.items() if 'kGB0' in d and 16 <= int(d['kGB0'][:2]) <= 55}
    simp = tgh1 | gb1
    syl = collections.defaultdict(list)          # syllable -> [(freq, order, char)]
    for c in simp:
        d = f[c]
        order = int(d['kGB0']) if 'kGB0' in d else 9000 + int(d['kTGH'].split(':')[1])
        if 'kHanyuPinlu' in d:
            for item in d['kHanyuPinlu'].split():
                r, n = item.rstrip(')').split('(')
                syl[plain(r)].append((int(n), order, c))
        else:
            for r in d.get('kMandarin', '').split()[:1]:
                syl[plain(r)].append((0, order, c))
    names = sorted(syl)
    out = ["/* Generated by sloppy-dev/kb/gen-pinyin.py from Unihan and pinyin-phrases.txt. Do not edit.",
           " * Every syllable, its characters by how often each is heard with that reading; then common words. */",
           "static const char *const py_syl[][2] = {"]
    for s in names:
        chars, seen = [], set()
        for n, o, c in sorted(syl[s], key=lambda t: (-t[0], t[1])):
            if c not in seen:
                seen.add(c)
                chars.append(chr(c))
        out.append('    { "%s", "%s" },' % (s, ''.join(chars)))
    out.append("};")
    phrases, pchars = [], set()
    for line in (HERE / 'pinyin-phrases.txt').read_text(encoding='utf-8').splitlines():
        if not line.strip() or line.startswith('#'):
            continue
        *py, hz = line.split()
        for p in py:
            if p not in syl:
                raise SystemExit(f"pinyin-phrases.txt: {p!r} is not a syllable ({line})")
        phrases.append((' '.join(py), hz))
        pchars |= {ord(ch) for ch in hz}
    out.append("/* syllables apart, then the word; the commonest first */")
    out.append("static const char *const py_words[][2] = {")
    seen = set()
    for py, hz in phrases:
        if (py, hz) in seen:
            continue
        seen.add((py, hz))
        out.append('    { "%s", "%s" },' % (py, hz))
    out.append("};")
    (ROOT / 'apps/sloppy/sloppy_pinyin.h').write_text('\n'.join(out) + '\n', encoding='utf-8')
    # the packs: simplified, then the traditional extras apart
    sys.path.insert(0, str(ROOT / 'sloppy-dev/lang'))
    from zh import ZH
    tr = set()
    for v in ZH.values():
        tr |= {ord(ch) for ch in v if ord(ch) >= 0x2e80}
    extra = set(range(0x3001, 0x3020)) | set(range(0x3041, 0x3097)) | set(range(0x30a1, 0x30fb)) | {0x30fc} | set(range(0xff01, 0xff5f))
    # and the rest of what Japanese titles use: the ideographic space, ・, the iteration
    # and sound marks, 〰 〽, the small kana for Ainu, half-width katakana
    extra |= {0x3000, 0x3030, 0x303d, 0x30a0} | set(range(0x309b, 0x30a0)) | set(range(0x30fb, 0x3100)) | set(range(0x31f0, 0x3200)) | set(range(0xff61, 0xffa0))
    main_set = simp | pchars | tr | extra | {0x62fc, 0x97f3}      # and 拼音, the keyboard's name
    # the extras pack: traditional forms of the common characters, and
    # Japan's common-use kanji (kJoyoKanji) the simplified set lacks
    trad = {c for c, d in f.items() if 'kJoyoKanji' in d and c not in main_set}
    for c in tgh1:
        for v in f[c].get('kTraditionalVariant', '').split():
            t = int(v[2:], 16)
            if t not in main_set:
                trad.add(t)
    (HERE / 'cjk-codepoints.txt').write_text('\n'.join('%x' % c for c in sorted(main_set)) + '\n')
    (HERE / 'cjkt-codepoints.txt').write_text('\n'.join('%x' % c for c in sorted(trad)) + '\n')
    print(f"{len(names)} syllables, {len(simp)} characters, {len(seen)} words; packs: {len(main_set)} + {len(trad)} traditional and Japanese")


if __name__ == '__main__':
    main()
