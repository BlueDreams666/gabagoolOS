// Rasterise a TTF into an LVGL 9 fmt_txt font (4 bpp, uncompressed), the same
// layout lv_font_conv writes. For machines without node/lv_font_conv:
//   swiftc -O ttf2lvgl.swift -o ttf2lvgl
//   ./ttf2lvgl SourceSans3-Regular.ttf 60 ss_regular_60 0x20-0x7E out.c [fallback]
import CoreGraphics
import CoreText
import Foundation

let a = CommandLine.arguments
guard a.count >= 6 else { print("usage: ttf2lvgl font.ttf size name ranges out.c [fallback]"); exit(1) }
let (path, size, name, ranges, out) = (a[1], Int(a[2])!, a[3], a[4], a[5])
let fallback = a.count > 6 ? a[6] : nil

var codes: [UInt32] = []
for r in ranges.split(separator: ",") {
    let p = r.split(separator: "-").map { UInt32($0.dropFirst(2), radix: 16)! }
    codes += Array(p[0]...(p.count > 1 ? p[1] : p[0]))
}

// TTF2LVGL_WGHT: a variable font's weight; TTF2LVGL_SCALE: its letters drawn
// that much bigger than the size named (Hebrew beside Latin, hebrew-fonts.py)
let env = ProcessInfo.processInfo.environment
let scale = Double(env["TTF2LVGL_SCALE"] ?? "") ?? 1
let provider = CGDataProvider(url: URL(fileURLWithPath: path) as CFURL)!
var font = CTFontCreateWithGraphicsFont(CGFont(provider)!, CGFloat(Double(size) * scale), nil, nil)
if let w = Double(env["TTF2LVGL_WGHT"] ?? "") {
    let d = CTFontDescriptorCreateWithAttributes([kCTFontVariationAttribute: [0x77676874: w]] as CFDictionary)   // 'wght'
    font = CTFontCreateCopyWithAttributes(font, CGFloat(Double(size) * scale), nil, d)
}
let ascent = CTFontGetAscent(font), descent = CTFontGetDescent(font)

struct G { var code: UInt32; var adv: Int; var w: Int; var h: Int; var ox: Int; var oy: Int; var px: [UInt8] }
var glyphs: [G] = []
let pad = size / 2 + 4
for c in codes {
    var u = [UniChar](String(UnicodeScalar(c)!).utf16)
    var g = [CGGlyph](repeating: 0, count: u.count)
    guard CTFontGetGlyphsForCharacters(font, &u, &g, u.count), g[0] != 0 else { continue }
    var adv = CGSize.zero
    CTFontGetAdvancesForGlyphs(font, .horizontal, &g, &adv, 1)
    let cw = size * 2 + pad * 2, ch = size * 2 + pad * 2
    var buf = [UInt8](repeating: 0, count: cw * ch)
    let ctx = CGContext(data: &buf, width: cw, height: ch, bitsPerComponent: 8, bytesPerRow: cw,
                        space: CGColorSpaceCreateDeviceGray(), bitmapInfo: CGImageAlphaInfo.none.rawValue)!
    ctx.setShouldAntialias(true); ctx.setAllowsFontSmoothing(false); ctx.setShouldSubpixelPositionFonts(false)
    ctx.setFillColor(gray: 1, alpha: 1)
    let origin = CGPoint(x: pad, y: pad + size / 2)          // baseline, from the bitmap's bottom
    var pos = origin
    CTFontDrawGlyphs(font, &g, &pos, 1, ctx)
    // CGContext rows run top-down in memory; find the ink box
    var x0 = cw, x1 = -1, y0 = ch, y1 = -1
    for y in 0..<ch { for x in 0..<cw where buf[y * cw + x] > 8 { x0 = min(x0, x); x1 = max(x1, x); y0 = min(y0, y); y1 = max(y1, y) } }
    var gl = G(code: c, adv: Int((adv.width * 16).rounded()), w: 0, h: 0, ox: 0, oy: 0, px: [])
    if x1 >= 0 {
        gl.w = x1 - x0 + 1; gl.h = y1 - y0 + 1
        gl.ox = x0 - pad
        let baselineRow = ch - 1 - (pad + size / 2)             // memory row of the baseline
        gl.oy = baselineRow - y1                                // bottom of ink above the baseline
        for y in y0...y1 { for x in x0...x1 { gl.px.append(buf[y * cw + x] >> 4) } }
    }
    glyphs.append(gl)
}

var s = """
/*******************************************************************************
 * Size: \(size) px
 * Bpp: 4
 * Opts: generated by sloppy-dev/ttf2lvgl.swift \((path as NSString).lastPathComponent) \(size) \(ranges)\(env["TTF2LVGL_WGHT"].map { " wght=\($0)" } ?? "")\(scale != 1 ? " scale=\(scale)" : "")
 ******************************************************************************/

#include "lvgl.h"

static LV_ATTRIBUTE_LARGE_CONST const uint8_t glyph_bitmap[] = {

"""
var index: [Int] = []
var total = 0
for g in glyphs {
    index.append(total)
    var bytes: [UInt8] = []
    var i = 0
    while i < g.px.count { bytes.append(g.px[i] << 4 | (i + 1 < g.px.count ? g.px[i + 1] : 0)); i += 2 }
    total += bytes.count
    s += "    /* U+\(String(format: "%04X", g.code)) */\n"
    for chunk in stride(from: 0, to: bytes.count, by: 16) {
        s += "    " + bytes[chunk..<min(chunk + 16, bytes.count)].map { String(format: "0x%02x,", $0) }.joined(separator: " ") + "\n"
    }
}
s += "};\n\nstatic const lv_font_fmt_txt_glyph_dsc_t glyph_dsc[] = {\n"
s += "    {.bitmap_index = 0, .adv_w = 0, .box_w = 0, .box_h = 0, .ofs_x = 0, .ofs_y = 0},\n"
for (i, g) in glyphs.enumerated() {
    s += "    {.bitmap_index = \(index[i]), .adv_w = \(g.adv), .box_w = \(g.w), .box_h = \(g.h), .ofs_x = \(g.ox), .ofs_y = \(g.oy)},\n"
}
s += "};\n\n"
let first = glyphs[0].code
s += "static const uint16_t unicode_list_0[] = {\n    " + glyphs.map { "0x\(String($0.code - first, radix: 16))," }.joined(separator: " ") + "\n};\n\n"
s += """
static const lv_font_fmt_txt_cmap_t cmaps[] = {
    {
        .range_start = \(first), .range_length = \(glyphs.last!.code - first + 1), .glyph_id_start = 1,
        .unicode_list = unicode_list_0, .glyph_id_ofs_list = NULL, .list_length = \(glyphs.count), .type = LV_FONT_FMT_TXT_CMAP_SPARSE_TINY
    }
};

static const lv_font_fmt_txt_dsc_t font_dsc = {
    .glyph_bitmap = glyph_bitmap, .glyph_dsc = glyph_dsc, .cmaps = cmaps,
    .kern_dsc = NULL, .kern_scale = 0, .cmap_num = 1, .bpp = 4, .kern_classes = 0, .bitmap_format = 0,
};

\(fallback.map { "extern const lv_font_t \($0);\n" } ?? "")
const lv_font_t \(name) = {
    .get_glyph_dsc = lv_font_get_glyph_dsc_fmt_txt,
    .get_glyph_bitmap = lv_font_get_bitmap_fmt_txt,
    .line_height = \(Int((ascent + descent).rounded(.up))),
    .base_line = \(Int(descent.rounded(.up))),
    .subpx = LV_FONT_SUBPX_NONE,
    .underline_position = -\(max(1, size / 20)),
    .underline_thickness = \(max(1, size / 20)),
    .dsc = &font_dsc,
    .fallback = \(fallback.map { "&\($0)" } ?? "NULL"),
    .user_data = NULL,
};

"""
try! s.write(toFile: out, atomically: true, encoding: .utf8)
print("\(name): \(glyphs.count) glyphs, \(total) bytes")
