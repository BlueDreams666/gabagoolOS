#!/usr/bin/env python3
"""Generate the Arabic companions of the SloppyOS UI fonts.

Each ss_<style>_<size> font falls back to ss_arabic_<size>, which falls
back to sl_xf_<size> (sloppy_xfont.inc: Cyrillic and Chinese, read from the
card when needed), which falls back to Montserrat for symbols. LVGL shapes Arabic itself
(LV_USE_ARABIC_PERSIAN_CHARS) by turning letters into their presentation
forms, so those forms are what the fonts carry. Only Noto Sans Arabic
Regular is in fonts-src: every weight uses it.

Needs lv_font_conv only (set LV_FONT_CONV, e.g. "node /path/lv_font_conv.js").
"""

import os
import re
import shlex
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "sloppy-dev" / "fonts-src" / "NotoSansArabic-Regular.ttf"
OUTPUT = ROOT / "apps" / "sloppy" / "fonts"
# letters, digits and punctuation, the presentation forms LVGL shapes to,
# and the Persian letters it knows
ARABIC_RANGE = ("0x600-0x6FF,0xFB56-0xFB59,0xFB7A-0xFB7D,0xFB8A-0xFB8B,"
                "0xFB8E-0xFB95,0xFBFC-0xFBFF,0xFE70-0xFEFC")
SIZES = {16: 16, 18: 18, 21: 20, 23: 22, 26: 24, 28: 28, 30: 28}   # size: Montserrat
UI_FONTS = ("bold_28", "regular_16", "regular_18", "semibold_18",
            "semibold_21", "semibold_23", "semibold_26", "semibold_30")


def main():
    converter = shlex.split(os.environ.get("LV_FONT_CONV", "lv_font_conv"))
    for size, fallback in SIZES.items():
        name = f"ss_arabic_{size}"
        out = OUTPUT / f"{name}.c"
        subprocess.run(converter + [
            "--font", str(SOURCE), "-r", ARABIC_RANGE,
            "--size", str(size), "--bpp", "4", "--format", "lvgl",
            "--no-compress", "--lv-include", "lvgl.h",
            "--lv-font-name", name,
            "--lv-fallback", f"sl_xf_{size}",
            "-o", str(out)], check=True)
        lines = out.read_text().splitlines(keepends=True)
        lines[3] = " * Opts: generated by sloppy-dev/generate-arabic-fonts.py (Noto Sans Arabic)\n"
        out.write_text("".join(lines))
        print(f"Generated {name}")
    for ui in UI_FONTS:
        path = OUTPUT / f"ss_{ui}.c"
        size = int(ui.split("_")[1])
        text = path.read_text()
        text = re.sub(r"\.fallback = &[a-z_0-9]+,", f".fallback = &ss_arabic_{size},", text)
        text = re.sub(r"extern const lv_font_t lv_font_montserrat_\d+;",
                      f"extern const lv_font_t ss_arabic_{size};", text)
        path.write_text(text)
        print(f"ss_{ui} falls back to ss_arabic_{size}")


if __name__ == "__main__":
    main()
