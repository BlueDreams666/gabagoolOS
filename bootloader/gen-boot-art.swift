// Renders the R1 boot menu's text and icons (Source Sans 3) into 4-bit alpha
// masks for bootloader/sloppy_boot_art.h. The bootloader has no font engine
// worth using at 311 ppi and must work when the card does not, so the art is
// compiled in. Run on a Mac:  swift bootloader/gen-boot-art.swift
import CoreGraphics
import CoreText
import Foundation

let root = URL(fileURLWithPath: #filePath).deletingLastPathComponent().deletingLastPathComponent()
let fonts = root.appendingPathComponent("sloppy-dev/fonts-src")

func font(_ file: String, _ px: CGFloat) -> CTFont {
    let url = fonts.appendingPathComponent(file) as CFURL
    let descs = CTFontManagerCreateFontDescriptorsFromURL(url) as! [CTFontDescriptor]
    return CTFontCreateWithFontDescriptor(descs[0], px, nil)
}

struct Mask { let name: String; let w: Int; let h: Int; let a: [UInt8] }
var masks: [Mask] = []

func render(_ name: String, w: Int, h: Int, _ draw: (CGContext) -> Void) {
    var px = [UInt8](repeating: 0, count: w * h)
    px.withUnsafeMutableBytes { buf in
        let ctx = CGContext(data: buf.baseAddress, width: w, height: h, bitsPerComponent: 8,
                            bytesPerRow: w, space: CGColorSpaceCreateDeviceGray(),
                            bitmapInfo: CGImageAlphaInfo.none.rawValue)!
        ctx.setAllowsAntialiasing(true)
        ctx.setShouldSmoothFonts(false)
        ctx.setFillColor(gray: 1, alpha: 1)
        ctx.setStrokeColor(gray: 1, alpha: 1)
        draw(ctx)
    }
    masks.append(Mask(name: name, w: w, h: h, a: px))
}

func text(_ name: String, _ s: String, _ f: CTFont, tracking: CGFloat = 0) {
    let attrs: [NSAttributedString.Key: Any] = [
        NSAttributedString.Key(kCTFontAttributeName as String): f,
        NSAttributedString.Key(kCTForegroundColorFromContextAttributeName as String): true,
        NSAttributedString.Key(kCTKernAttributeName as String): tracking]
    let line = CTLineCreateWithAttributedString(NSAttributedString(string: s, attributes: attrs))
    var ascent: CGFloat = 0, descent: CGFloat = 0
    let width = CTLineGetTypographicBounds(line, &ascent, &descent, nil)
    let w = Int(ceil(width)) + 2, h = Int(ceil(ascent + descent)) + 2
    render(name, w: w, h: h) { ctx in
        ctx.textPosition = CGPoint(x: 1, y: 1 + descent)
        CTLineDraw(line, ctx)
    }
}

let bold = "SourceSans3-Bold.ttf", semi = "SourceSans3-Semibold.ttf", reg = "SourceSans3-Regular.ttf"
text("wordmark", "GabagoolOS", font(bold, 76), tracking: -1.5)
text("tagline", "Choose what to start", font(reg, 26))
text("t_sloppy", "GabagoolOS", font(semi, 38))
text("t_hiby", "HiBy Player", font(semi, 38))
text("t_tools", "Tools", font(semi, 38))
text("s_sloppy", "Your music, your way", font(reg, 23))
text("s_hiby", "The stock HiBy firmware", font(reg, 23))
text("s_tools", "USB, ADB and recovery", font(reg, 23))
text("st_sloppy", "Starting GabagoolOS in", font(reg, 23))
text("st_hiby", "Starting HiBy Player in", font(reg, 23))
text("st_tools", "Opening Tools in", font(reg, 23))
for d in 0...9 { text("d\(d)", "\(d)", font(semi, 23)) }
text("hint", "Volume + / \u{2212}  choose      Next  start", font(reg, 21))

// Icons, 56 px, drawn as plain paths (no symbol fonts).
let icon = 56
render("i_sloppy", w: icon, h: icon) { c in            // two beamed eighth notes
    c.fillEllipse(in: CGRect(x: 6, y: 6, width: 17, height: 13))
    c.fillEllipse(in: CGRect(x: 31, y: 11, width: 17, height: 13))
    c.fill(CGRect(x: 19, y: 12, width: 5, height: 34))
    c.fill(CGRect(x: 44, y: 17, width: 5, height: 34))
    c.beginPath()
    c.move(to: CGPoint(x: 19, y: 39)); c.addLine(to: CGPoint(x: 49, y: 46))
    c.addLine(to: CGPoint(x: 49, y: 54)); c.addLine(to: CGPoint(x: 19, y: 47))
    c.closePath(); c.fillPath()
}
render("i_hiby", w: icon, h: icon) { c in              // a little player: screen and wheel
    c.setLineWidth(4.5)
    c.addPath(CGPath(roundedRect: CGRect(x: 12, y: 3, width: 32, height: 50), cornerWidth: 7, cornerHeight: 7, transform: nil))
    c.strokePath()
    c.fill(CGRect(x: 18, y: 33, width: 20, height: 13))
    c.strokeEllipse(in: CGRect(x: 20, y: 9, width: 16, height: 16))
}
render("i_tools", w: icon, h: icon) { c in             // three sliders
    for (i, k) in [(0, 36.0), (1, 16.0), (2, 30.0)] {
        let y = 12.0 + Double(i) * 16
        c.fill(CGRect(x: 6, y: y - 2, width: 44, height: 4))
        c.fillEllipse(in: CGRect(x: k - 7, y: y - 7, width: 14, height: 14))
    }
}

// 4-bit alpha, two pixels a byte (high nibble first), rows top to bottom.
var out = """
/* Generated by bootloader/gen-boot-art.swift from Source Sans 3 (SIL OFL,
 * sloppy-dev/fonts-src). Do not edit; run the generator. */
#ifndef SLOPPY_BOOT_ART_H
#define SLOPPY_BOOT_ART_H
struct sb_mask { short w, h; const unsigned char *a; };

"""
var total = 0
for m in masks {
    let stride = (m.w + 1) / 2
    var bytes = [UInt8](repeating: 0, count: stride * m.h)
    for y in 0..<m.h {
        let src = y                           // bitmap memory is top row first
        for x in 0..<m.w {
            let v = UInt8((Int(m.a[src * m.w + x]) * 15 + 127) / 255)
            bytes[y * stride + x / 2] |= x % 2 == 0 ? v << 4 : v
        }
    }
    total += bytes.count
    out += "static const unsigned char sb_\(m.name)_a[] = {"
    for (i, b) in bytes.enumerated() { out += (i % 24 == 0 ? "\n    " : "") + String(format: "0x%02x,", b) }
    out += "\n};\nstatic const struct sb_mask sb_\(m.name) = { \(m.w), \(m.h), sb_\(m.name)_a };\n"
}
out += "static const struct sb_mask *const sb_digits[10] = {\n   "
for d in 0...9 { out += " &sb_d\(d)," }
out += "\n};\n#endif\n"
try! out.write(to: root.appendingPathComponent("bootloader/sloppy_boot_art.h"), atomically: true, encoding: .utf8)
print("wrote \(masks.count) masks, \(total) bytes")
