/* A Game Boy cartridge for the harness, assembled by hand: no game, nobody's
 * copyright. It draws stripes, beeps a square wave, scrolls one pixel a
 * frame, puts the held d-pad in the vertical scroll and in its battery RAM,
 * and marks that RAM with 0x42. color: flagged for the Game Boy Color, with
 * a palette of white, red, green and blue. */
#include <stdint.h>
#include <string.h>
static const uint8_t gbt_code[] = {
    0xF3, 0x31, 0xFE, 0xFF, 0xAF, 0xE0, 0x40,             /* 0150 di; sp; LCD off */
    0x21, 0x10, 0x80, 0x06, 0x10, 0x3E, 0xFF, 0x22, 0x05, 0x20, 0xFC,   /* tile 1: solid */
    0x06, 0x08, 0x3E, 0xAA, 0x22, 0x3E, 0x55, 0x22, 0x05, 0x20, 0xF7,   /* tile 2: checks */
    0x21, 0x00, 0x98, 0x01, 0x00, 0x04, 0x7D, 0xE6, 0x01, 0x3C, 0x22,   /* the map: 1, 2, 1, 2 */
    0x0B, 0x78, 0xB1, 0x20, 0xF6,
    0x3E, 0xE4, 0xE0, 0x47,                                /* BGP */
    0x3E, 0x80, 0xE0, 0x68, 0x21, 0xDD, 0x01, 0x06, 0x08, 0x2A, 0xE0, 0x69, 0x05, 0x20, 0xFA,  /* CGB palette 0 */
    0x3E, 0x80, 0xE0, 0x26, 0x3E, 0x77, 0xE0, 0x24, 0x3E, 0x11, 0xE0, 0x25,   /* sound on */
    0x3E, 0x80, 0xE0, 0x11, 0x3E, 0xF0, 0xE0, 0x12, 0x3E, 0x00, 0xE0, 0x13, 0x3E, 0x87, 0xE0, 0x14,
    0x3E, 0x0A, 0xEA, 0x00, 0x00, 0x3E, 0x42, 0xEA, 0x00, 0xA0,   /* battery RAM on, 0x42 at A000 */
    0x3E, 0x91, 0xE0, 0x40,                                /* LCD on */
    0xF0, 0x44, 0xFE, 0x90, 0x20, 0xFA,                    /* 01BA: wait for line 144 */
    0xF0, 0x43, 0x3C, 0xE0, 0x43,                          /* SCX + 1 */
    0x3E, 0x20, 0xE0, 0x00, 0xF0, 0x00, 0xF0, 0x00, 0x2F, 0xE6, 0x0F,   /* the d-pad */
    0xE0, 0x42, 0xEA, 0x01, 0xA0,                          /* into SCY and A001 */
    0xF0, 0x44, 0xFE, 0x90, 0x28, 0xFA,                    /* wait to leave line 144 */
    0x18, 0xDD,                                            /* again */
    0xFF, 0x7F, 0x1F, 0x00, 0xE0, 0x03, 0x00, 0x7C,        /* 01DD: white, red, green, blue */
};
static void gbt_make(uint8_t *rom /* 32 KB */, const char *title, int color)
{
    memset(rom, 0, 32768);
    rom[0x100] = 0x00; rom[0x101] = 0xC3; rom[0x102] = 0x50; rom[0x103] = 0x01;   /* nop; jp 0150 */
    strncpy((char *)rom + 0x134, title, 15);
    rom[0x143] = color ? 0x80 : 0x00;
    rom[0x147] = 0x03;                                     /* MBC1 + RAM + battery */
    rom[0x148] = 0x00;                                     /* 32 KB */
    rom[0x149] = 0x02;                                     /* 8 KB of RAM */
    memcpy(rom + 0x150, gbt_code, sizeof gbt_code);
}
