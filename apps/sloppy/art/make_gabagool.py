"""Crop gabagool.jpg and embed it as the Gabagool tile's RGB565 photos.

Run on macOS (it uses sips): python3 make_gabagool.py
"""
from pathlib import Path
import struct
import subprocess
import tempfile

HERE = Path(__file__).parent
# name: (square crop size, crop x, crop y, output size)
CROPS = {
    "gb_photo_219": (435, 12, 0, 219),   # all of it, less the door frame on the left
    "gb_photo_104": (290, 82, 0, 104),   # the face and the shirt, for the small tile
    "gb_photo_58": (290, 82, 0, 58),     # and for lists
}


def read_bmp(path: Path, size: int):
    data = path.read_bytes()
    offset = struct.unpack_from("<I", data, 10)[0]
    width, height, planes, depth = struct.unpack_from("<iiHH", data, 18)
    if data[:2] != b"BM" or planes != 1 or depth not in (24, 32) or width != size or abs(height) != size:
        raise ValueError(f"expected a {size}x{size} 24/32-bit BMP: {path}")
    stride = ((width * depth + 31) // 32) * 4
    pixels = []
    for y in range(size):
        row = offset + (y if height < 0 else size - 1 - y) * stride
        for x in range(size):
            b, g, r = data[row + x * (depth // 8):row + x * (depth // 8) + 3]
            pixels.append(((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3))
    return pixels


with (HERE / "gabagool_photo.inc").open("w") as f:
    f.write("/* Generated by art/make_gabagool.py from art/gabagool.jpg; RGB565. */\n")
    for name, (crop, x, y, size) in CROPS.items():
        with tempfile.TemporaryDirectory() as d:
            cropped, bmp = Path(d) / "crop.jpg", Path(d) / "out.bmp"
            subprocess.run(["sips", "-c", str(crop), str(crop), "--cropOffset", str(y), str(x),
                            str(HERE / "gabagool.jpg"), "--out", str(cropped)], check=True, stdout=subprocess.DEVNULL)
            subprocess.run(["sips", "-z", str(size), str(size), "-s", "format", "bmp",
                            str(cropped), "--out", str(bmp)], check=True, stdout=subprocess.DEVNULL)
            px = read_bmp(bmp, size)
        f.write(f"static const uint16_t {name}[{size} * {size}] = {{\n")
        for i in range(0, len(px), 16):
            f.write("    " + ", ".join(f"0x{p:04x}" for p in px[i:i + 16]) + ",\n")
        f.write("};\n")
